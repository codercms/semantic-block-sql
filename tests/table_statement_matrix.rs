#[test]
fn restored_table_shapes_have_explicit_golden_layout() {
    support::assert_cases(&[
        support::SqlCase::new(
            "replica identity",
            "alter table lab.readings replica identity full;",
            "ALTER TABLE lab.readings REPLICA IDENTITY FULL;",
        ),
        support::SqlCase::new(
            "inheritance",
            "alter table lab.readings inherit lab.measurements;",
            "ALTER TABLE lab.readings INHERIT lab.measurements;",
        ),
        support::SqlCase::new(
            "typed table",
            "alter table lab.readings of lab.reading_type;",
            "ALTER TABLE lab.readings OF lab.reading_type;",
        ),
        support::SqlCase::new(
            "remove type",
            "alter table lab.readings not of;",
            "ALTER TABLE lab.readings NOT OF;",
        ),
        support::SqlCase::new(
            "constraint properties",
            "alter table lab.readings alter constraint reading_ref deferrable initially deferred;",
            "ALTER TABLE lab.readings ALTER CONSTRAINT reading_ref DEFERRABLE INITIALLY DEFERRED;",
        ),
        support::SqlCase::new(
            "partition column options",
            "create table lab.child partition of lab.readings (score with options not null) for values from (10) to (20);",
            "CREATE TABLE lab.child PARTITION OF lab.readings (\n    score WITH OPTIONS NOT NULL\n)\nFOR VALUES FROM (10) TO (20);",
        ),
        support::SqlCase::new(
            "keyword-like table name",
            "create table lab.tablespace (id int);",
            "CREATE TABLE lab.tablespace (\n    id int\n);",
        ),
    ]);
}

#[test]
fn guarded_actions_keep_comments_blank_groups_and_crlf() {
    let source = "ALTER TABLE lab.readings\n    DROP COLUMN IF EXISTS legacy_value, -- obsolete value\n    DROP COLUMN IF EXISTS legacy_unit,\n\n    -- old uniqueness rule\n    DROP CONSTRAINT IF EXISTS reading_key;";
    support::assert_sql(source, source);
    let crlf = source.replace('\n', "\r\n");
    let formatted = semblock::source::format_source(
        &crlf,
        semblock::source::Language::Sql,
        &FormatOptions::default(),
        &semblock::config::GoConfig::default(),
    )
    .unwrap();
    assert_eq!(formatted.output, crlf);
}

#[test]
fn table_check_and_default_expressions_obey_hard_width() {
    let options = FormatOptions {
        soft_line_width: 65,
        hard_line_width: 90,
        ..Default::default()
    };
    for source in [
        "CREATE TABLE lab.readings (score int, note text, CHECK ((score > 0 AND note IS NOT NULL AND length(note) > 20) OR (score = 0 AND note IS NULL)));",
        "ALTER TABLE lab.readings DROP COLUMN IF EXISTS legacy_value, ADD CONSTRAINT score_range CHECK (score > 0 AND score < 100 AND note IS NOT NULL AND length(note) > 5);",
    ] {
        let result = format_sql(source, &options).unwrap();
        assert!(
            result
                .diagnostics
                .iter()
                .all(|diagnostic| diagnostic.fix_available),
            "{:?}",
            result.diagnostics
        );
        assert!(result.warnings.is_empty());
        assert!(
            result.output.lines().all(|line| line.chars().count() <= 90),
            "{}",
            result.output
        );
        validate_equivalent(source, &result.output).unwrap();
        assert_eq!(
            result.output,
            format_sql(&result.output, &options).unwrap().output
        );
    }
}

