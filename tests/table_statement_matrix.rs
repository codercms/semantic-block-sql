mod support;

use semblock::{FormatOptions, UnsupportedPolicy, check_sql, format_sql, validate_equivalent};

fn assert_reviewed_statements(cases: &[&str]) {
    let options = FormatOptions {
        unsupported_policy: UnsupportedPolicy::Error,
        ..Default::default()
    };
    let mut failures = Vec::new();
    for source in cases {
        let result = match format_sql(source, &options) {
            Ok(result) => result,
            Err(error) => {
                failures.push(format!("{source}\n{error}"));
                continue;
            }
        };
        let rejected = result
            .diagnostics
            .iter()
            .filter(|diagnostic| !diagnostic.fix_available)
            .collect::<Vec<_>>();
        if !rejected.is_empty() || !result.warnings.is_empty() {
            failures.push(format!("{source}\n{rejected:?}\n{:?}", result.warnings));
            continue;
        }
        validate_equivalent(source, &result.output).unwrap();
        let mut lowercase_keywords = source.to_string();
        for token in pg_query::scan(source).unwrap().tokens.into_iter().rev() {
            if pg_query::protobuf::KeywordKind::try_from(token.keyword_kind).unwrap()
                != pg_query::protobuf::KeywordKind::NoKeyword
            {
                let range = token.start as usize..token.end as usize;
                lowercase_keywords
                    .replace_range(range.clone(), &source[range].to_ascii_lowercase());
            }
        }
        let lowercase = format_sql(&lowercase_keywords, &options).unwrap();
        if lowercase.output != result.output {
            failures.push(format!(
                "{source}\nkeyword casing differs:\n{}\nexpected:\n{}",
                lowercase.output, result.output
            ));
            continue;
        }
        let second = format_sql(&result.output, &options).unwrap();
        assert_eq!(result.output, second.output, "{source}");
        assert!(
            check_sql(&result.output, &options).compliant,
            "{}",
            result.output
        );
    }
    assert!(failures.is_empty(), "{}", failures.join("\n\n"));
}

