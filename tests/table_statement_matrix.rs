#[test]
fn ddl_grammar_roles_preserve_names_and_quoted_storage_modes() {
    for (source, expected) in [
        (
            "alter table lab.readings set access method access;",
            "ALTER TABLE lab.readings SET ACCESS METHOD access;",
        ),
        (
            "alter table lab.readings enable replica trigger replica;",
            "ALTER TABLE lab.readings ENABLE REPLICA TRIGGER replica;",
        ),
        (
            "alter table lab.readings owner to comment;",
            "ALTER TABLE lab.readings OWNER TO comment;",
        ),
        (
            "alter table lab.readings cluster on options;",
            "ALTER TABLE lab.readings CLUSTER ON options;",
        ),
        (
            "alter table lab.readings alter column external set storage external;",
            "ALTER TABLE lab.readings ALTER COLUMN external SET STORAGE EXTERNAL;",
        ),
        (
            "alter table lab.readings alter column note set storage \"external\";",
            "ALTER TABLE lab.readings ALTER COLUMN note SET STORAGE \"external\";",
        ),
        (
            "create table lab.readings (compression text compression lz4, stored text, comment text default 'SET STORAGE external');",
            "CREATE TABLE lab.readings (\n    compression text COMPRESSION lz4,\n    stored text,\n    comment text DEFAULT 'SET STORAGE external'\n);",
        ),
    ] {
        support::assert_sql(source, expected);
    }
    for mode in ["plain", "main", "extended", "external"] {
        support::assert_sql(
            &format!("alter table lab.readings alter column note set storage {mode};"),
            &format!(
                "ALTER TABLE lab.readings ALTER COLUMN note SET STORAGE {};",
                mode.to_uppercase()
            ),
        );
    }
    support::assert_sql(
        "select gist(1), comment(2) from lab.readings;",
        "SELECT gist(1), comment(2) FROM lab.readings;",
    );
}

